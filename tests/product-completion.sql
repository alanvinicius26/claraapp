 perform public.manage_booking(token,'cancel');
 update public.working_hours set enabled=false where studio_id=sid;
 slots:=public.available_dates_multi(original,array[svc],d-1,d+20);
 if jsonb_array_length(slots->'dates')<>0 or (slots->>'hasMore')::boolean then raise exception 'Horizon not enforced'; end if;
end $$;
