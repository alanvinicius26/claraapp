do $$
declare uid uuid:=gen_random_uuid(); other_uid uuid:=gen_random_uuid(); sid uuid; other_sid uuid;
 svc uuid; source_id uuid; target_id uuid; foreign_id uuid; booking jsonb; slots jsonb; rejected boolean;
 original text:='qa-product-'||gen_random_uuid()::text; renamed text:='qa-new-'||gen_random_uuid()::text;
 d date:=(now() at time zone 'America/Sao_Paulo')::date+2; first_time timestamptz; aid uuid; token uuid;
begin
 insert into auth.users(id,email) values(uid,uid::text||'@example.invalid'),(other_uid,other_uid::text||'@example.invalid');
 insert into public.studios(owner_id,name,professional,slug,horizon,min_notice,buffer) values(uid,'QA','QA',original,7,0,15) returning id into sid;
 insert into public.studios(owner_id,name,professional,slug) values(other_uid,'Other QA','QA','qa-other-'||other_uid::text) returning id into other_sid;
 insert into public.working_hours(studio_id,weekday) select sid,generate_series(0,6);
