 begin update public.studios set slug=original where id=other_sid;
 exception when raise_exception then rejected:=true; end;
 if not rejected then raise exception 'Old URL takeover allowed'; end if;
 slots:=public.available_dates_multi(original,array[svc],d-1,d+20);
 if jsonb_array_length(slots->'dates')<>3 then raise exception 'Expected three dates'; end if;
 first_time:=(slots->'dates'->0->>'first')::timestamptz;
 if (slots->'dates'->0->>'date')::date<>d then raise exception 'Unexpected first date'; end if;
 booking:=public.book_appointment_multi(original,array[svc],first_time,'QA Client','','+55 (11) 99999-8888','');
 aid:=(booking->>'id')::uuid; token:=(booking->>'token')::uuid;
 select client_id into source_id from public.appointments where id=aid;
